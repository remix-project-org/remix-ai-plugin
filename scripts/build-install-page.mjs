// Writes docs/ai-tools.html: assets/install.html filled in for the full build at BASE_URL,
// without analytics, so the page can be hosted anywhere. Edit the template, not the copy.
//   tsx --env-file=.env_main scripts/build-install-page.mjs
import fs from "fs";
import path from "path";
import { renderPage } from "../src/pages.ts";

const baseUrl = process.env.BASE_URL?.replace(/\/$/, "");
if (!baseUrl || !baseUrl.startsWith("https://")) {
  console.error("Set BASE_URL to the full build's public https URL (in .env_main or the environment) before building the page.");
  process.exit(1);
}

const root = path.resolve(import.meta.dirname, "..");
const template = fs.readFileSync(path.join(root, "assets/install.html"), "utf-8");
const html = renderPage(template, { baseUrl, full: true }).replace(
  "<!doctype html>",
  "<!doctype html>\n<!-- Generated by scripts/build-install-page.mjs from assets/install.html. Do not edit; edit the template and rebuild. -->",
);

const out = path.join(root, "docs/ai-tools.html");
fs.writeFileSync(out, html);
console.log(`Wrote ${path.relative(process.cwd(), out)} → ${baseUrl}`);
